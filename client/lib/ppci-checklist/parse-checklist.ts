/** One row of a sheet: column letter → cell text. */
export type SheetRow = Map<string, string>;

export type ChecklistItem = {
  text: string;
  /** The sub-heading the item sits under inside its group, such as "RTI". */
  section?: string;
  /** The normative passage the item cites, such as "Art.10 da IN06". */
  reference?: string;
};

export type ChecklistGroup = {
  name: string;
  items: ChecklistItem[];
  /** The item count the sheet's control panel shows for the group. */
  panelCount: number;
};

const unescapeXml = (text: string) =>
  text
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");

/** Rows of an .xlsx sheet by row number, from its sheet and shared strings XML. */
export function readSheet(sheetXml: string, sharedStringsXml: string) {
  const strings = [...sharedStringsXml.matchAll(/<si>([\s\S]*?)<\/si>/g)].map(
    (si) =>
      unescapeXml(
        [...si[1].matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)]
          .map((t) => t[1])
          .join(""),
      ),
  );
  const rows = new Map<number, SheetRow>();
  for (const row of sheetXml.matchAll(
    /<row [^>]*r="(\d+)"[^>]*>([\s\S]*?)<\/row>/g,
  )) {
    const cells: SheetRow = new Map();
    for (const cell of row[2].matchAll(
      /<c r="([A-Z]+)\d+"([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g,
    )) {
      const value = cell[3]?.match(/<v>([\s\S]*?)<\/v>/)?.[1];
      if (value === undefined) continue;
      cells.set(
        cell[1],
        /t="s"/.test(cell[2]) ? strings[Number(value)] : unescapeXml(value),
      );
    }
    if (cells.size > 0) rows.set(Number(row[1]), cells);
  }
  return rows;
}

const clean = (text: string) => text.replace(/\s+/g, " ").trim();

const REFERENCE =
  /(?:(?:Art\.?\s?\d+|tabela \d+|anexo [A-Z])\s+da\s+)?IN\s?\d+(?:\s+parte \d)?/i;

export function itemReference(text: string): string | undefined {
  return text.match(REFERENCE)?.[0];
}

const NOT_APPLICABLE = "Não possui este sistema";

/**
 * The groups and items of Moura's "Check list de projetos" sheet, in sheet
 * order. The control panel at the top names each group (column A) with a count
 * (column F); further down, a row with only that name opens the group. Inside
 * it, a row with status cells (A to C) and text in D is an item, a row with
 * only text in D is a sub-heading for the items after it, and the header row
 * and the "Não possui este sistema" switch are skipped.
 */
export function parseChecklist(rows: Map<number, SheetRow>): ChecklistGroup[] {
  const ordered = [...rows.entries()].sort(([a], [b]) => a - b);
  const panel = new Map<string, number>();
  for (const [, row] of ordered) {
    const name = row.get("A");
    const count = Number(row.get("F"));
    if (name && name !== "TOTAL" && row.has("F") && Number.isInteger(count)) {
      panel.set(clean(name), count);
    }
  }

  const groups: ChecklistGroup[] = [];
  let current: ChecklistGroup | undefined;
  let section: string | undefined;
  for (const [, row] of ordered) {
    const a = row.get("A");
    const d = row.get("D");
    const name = a && clean(a);
    if (name && panel.has(name) && !d && !row.has("F")) {
      current = { name, items: [], panelCount: panel.get(name) ?? 0 };
      groups.push(current);
      section = undefined;
      continue;
    }
    if (!current || !d) continue;
    const text = clean(d);
    const hasStatus = row.has("B") || row.has("C");
    if (text === NOT_APPLICABLE || (hasStatus && Number.isNaN(Number(a)))) {
      continue;
    }
    if (!hasStatus && !row.has("A")) {
      section = text;
      continue;
    }
    const reference = itemReference(text);
    current.items.push({
      text,
      ...(section && { section }),
      ...(reference && { reference }),
    });
  }

  const missing = [...panel.keys()].filter(
    (name) => !groups.some((group) => group.name === name),
  );
  if (missing.length > 0) {
    throw new Error(`Groups not found in the sheet: ${missing.join(", ")}`);
  }
  return groups;
}

const sqlText = (text: string) => `'${text.replace(/'/g, "''")}'`;
const optional = (text?: string) => (text ? sqlText(text) : "null");

/** The migration that seeds one checklist version, groups and items in sheet order. */
export function checklistSeedSql(version: string, groups: ChecklistGroup[]) {
  const groupRows = groups.map(
    (group, index) =>
      `  (${sqlText(version)}, ${index + 1}, ${sqlText(group.name)})`,
  );
  const itemRows = groups.flatMap((group, groupIndex) =>
    group.items.map(
      (item, index) =>
        `  (${sqlText(version)}, ${groupIndex + 1}, ${index + 1}, ${optional(item.section)}, ${sqlText(item.text)}, ${optional(item.reference)})`,
    ),
  );
  return `-- Generated by client/scripts/import-ppci-checklist.mjs from Moura's
-- "Check list de projetos" sheet. Do not edit by hand; import a new version.

insert into public.ppci_checklists (version) values (${sqlText(version)});

insert into public.ppci_checklist_groups (checklist_version, position, name) values
${groupRows.join(",\n")};

insert into public.ppci_checklist_items (checklist_version, group_position, position, section, text, reference) values
${itemRows.join(",\n")};
`;
}
